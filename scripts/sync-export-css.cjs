// Keep file:// HTML exports in sync without requiring a server or runtime fetch.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const css = fs.readFileSync(path.join(root, "styles/app.css"), "utf8");
const output = '"use strict";\n// Generated by node scripts/sync-export-css.cjs; edit styles/app.css instead.\n'
  + `const EXPORT_CSS = ${JSON.stringify(css).replace(/</g, "\\u003c")};\n`;
const destination = path.join(root, "src/export-styles.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== output) {
    console.error("Export CSS is out of date. Run node scripts/sync-export-css.cjs");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(destination, output);
}
